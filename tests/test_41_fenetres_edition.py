"""2026.5.38 : editions et creations en fenetres en surimpression, saisie protegee.
Un editeur ou un formulaire de creation s'ouvre au-dessus de la liste (qui ne bouge pas),
une seule largeur pour toutes les fenetres (2026.5.39), plein ecran sur telephone. Tant que rien n'est tape, clic a cote
ou Echap ferment ; apres une saisie, la fenetre reste ouverte et un avis s'affiche ; ✕ et
Annuler ferment toujours. Meme protection pour Reglages et Scinder un lot."""
import sys; from harnais import ouvrir, Resultats; from donnees import construire
from outils_page import *
R = Resultats()
D, ids_mat, ids_lot = construire()
def ouvert(page, sel): return page.evaluate("s => { const e = document.querySelector(s); return !!e && e.classList.contains('en-fenetre'); }", sel)
def voile(page): return page.evaluate("() => { const v = document.getElementById('voileFenetre'); return !!v && !v.hidden; }")
def clic_voile(page): page.mouse.click(8, 450); page.wait_for_timeout(120)
with ouvrir(D) as page:
    page.set_viewport_size({"width": 1440, "height": 700})
    page.evaluate("() => naviguer('materiel')"); page.wait_for_timeout(250)
    page.evaluate("() => document.querySelectorAll('#materiel-list .lot').forEach(l => l.classList.add('open'))"); page.wait_for_timeout(100)
    page.evaluate("() => window.scrollTo(0, 300)"); page.wait_for_timeout(80)
    y0 = page.evaluate("window.scrollY")
    # ---- editeur ouvert depuis la liste
    page.evaluate("id => document.querySelector('#materiel-list .btn-edit[data-ent=\"materiel\"][data-id=\"' + id + '\"]').click()", ids_mat["CAS-002"]); page.wait_for_timeout(200)
    R.verifier(ouvert(page, "#materiel-editor") and voile(page), "editeur : ouvert en fenetre, voile affiche")
    R.verifier(page.evaluate("getComputedStyle(document.getElementById('materiel-editor')).position") == "fixed", "editeur : position fixe (au-dessus de la liste)")
    R.verifier(page.evaluate("window.scrollY") == y0, "la liste ne bouge pas : defilement conserve (%s -> %s)" % (y0, page.evaluate("window.scrollY")))
    R.verifier(sa(page.inner_text("#materiel-editor .fenetre-action")) == "modifier l'exemplaire" and
               "cas-002" in sa(page.inner_text("#materiel-editor .fenetre-objet")) and "casques boreo" in sa(page.inner_text("#materiel-editor .fenetre-objet")),
               "editeur : titre = action + objet (marquage et lot)")
    w = page.evaluate("document.getElementById('materiel-editor').getBoundingClientRect().width")
    R.verifier(w == 1040, "editeur : largeur commune des fenetres (%d px)" % w)
    clic_voile(page)
    R.verifier(not ouvert(page, "#materiel-editor") and not voile(page), "sans saisie : un clic a cote ferme")
    # ---- saisie en cours : protege
    page.evaluate("id => openEditor('materiel', id)", ids_mat["CAS-002"]); page.wait_for_timeout(150)
    page.fill('#materiel-editor [data-f="commentaire"]', "Note en cours"); page.wait_for_timeout(50)
    clic_voile(page)
    R.verifier(ouvert(page, "#materiel-editor"), "apres saisie : le clic a cote ne ferme pas")
    R.verifier(page.is_visible("#avisSaisie") and "annuler" in sa(page.inner_text("#avisSaisie")), "apres saisie : avis « fermez avec Annuler ou ✕ »")
    R.verifier(page.input_value('#materiel-editor [data-f="commentaire"]') == "Note en cours", "la saisie est intacte")
    page.keyboard.press("Escape"); page.wait_for_timeout(100)
    R.verifier(ouvert(page, "#materiel-editor"), "apres saisie : Echap ne ferme pas non plus")
    page.click("#materiel-editor .fenetre-fermer"); page.wait_for_timeout(120)
    R.verifier(not ouvert(page, "#materiel-editor") and not voile(page), "✕ ferme toujours")
    page.evaluate("id => openEditor('materiel', id)", ids_mat["CAS-002"]); page.wait_for_timeout(150)
    page.keyboard.press("Escape"); page.wait_for_timeout(100)
    R.verifier(not ouvert(page, "#materiel-editor"), "reouverture propre : Echap ferme (saisie oubliee)")
    page.evaluate("id => openEditor('materiel', id)", ids_mat["CAS-002"]); page.wait_for_timeout(150)
    page.fill('#materiel-editor [data-f="commentaire"]', "x")
    page.click("#materiel-editor .ed-cancel"); page.wait_for_timeout(120)
    R.verifier(not ouvert(page, "#materiel-editor"), "Annuler ferme toujours, meme avec une saisie")
    # ---- (2026.5.40) fiche : la barre des petits formulaires imbriques garde son aspect normal
    page.evaluate("id => { ouvrirFicheExemplaire(id); ficheAction(id, 'controler', null); }", ids_mat["CAS-001"]); page.wait_for_timeout(250)
    st = page.evaluate("""() => { const fa = document.querySelector('#ficheAction .form-actions'), qa = fa.parentElement;
        return [getComputedStyle(fa).position, Math.round(fa.getBoundingClientRect().right - qa.getBoundingClientRect().right)]; }""")
    R.verifier(st[0] != "sticky" and st[1] <= 0, "fiche, mini-formulaire : barre de boutons normale, sans debordement %s" % st)
    page.evaluate("fermerEditeurs()"); page.wait_for_timeout(100)
    # ---- formulaire de creation : large, titre, Annuler
    page.evaluate("() => naviguer('prets')"); page.wait_for_timeout(200)
    page.click("#btnTogglePret"); page.wait_for_timeout(150)
    R.verifier(ouvert(page, "#formPret"), "nouveau pret : en fenetre")
    wl = page.evaluate("document.getElementById('formPret').getBoundingClientRect().width")
    R.verifier(wl == 1040, "nouveau pret : meme largeur que les autres fenetres (%d px)" % wl)
    tp = sa(page.inner_text("#formPret .fenetre-titre"))
    R.verifier("nouveau pret" in tp and "bon n" in tp, "nouveau pret : titre (action + numero du bon) : %r" % tp)
    # changement de rubrique (par le menu, comme le fait l'application) : la fenetre de l'autre rubrique ne reste pas affichee
    page.evaluate("() => naviguer('materiel')"); page.wait_for_timeout(150)
    R.verifier(not voile(page), "autre rubrique : pas de voile orphelin")
    page.evaluate("() => naviguer('prets')"); page.wait_for_timeout(150)
    R.verifier(ouvert(page, "#formPret") and voile(page), "retour dans Prets : le formulaire est toujours ouvert")
    page.click("#btnCancelPret"); page.wait_for_timeout(120)
    R.verifier(not ouvert(page, "#formPret") and not voile(page), "Annuler du formulaire de creation : ferme")
    # ---- Reglages : meme protection
    page.evaluate("ouvrirReglages()"); page.wait_for_timeout(120)
    wr = page.evaluate("document.querySelector('#reglagesPanel .reglages-modale').getBoundingClientRect().width")
    R.verifier(wr == 1040, "Reglages : meme largeur que les autres fenetres (%d px)" % wr)
    page.mouse.click(8, 450); page.wait_for_timeout(100)
    R.verifier(page.evaluate("document.getElementById('reglagesPanel').hidden"), "Reglages sans saisie : un clic a cote ferme")
    page.evaluate("ouvrirReglages()"); page.wait_for_timeout(120)
    page.fill('#reglagesCorps input[data-cle="titre_appli"]', "Titre en cours")
    page.mouse.click(8, 450); page.wait_for_timeout(100)
    R.verifier(not page.evaluate("document.getElementById('reglagesPanel').hidden"), "Reglages apres saisie : le clic a cote ne ferme pas")
    page.keyboard.press("Escape"); page.wait_for_timeout(100)
    R.verifier(not page.evaluate("document.getElementById('reglagesPanel').hidden"), "Reglages apres saisie : Echap ne ferme pas")
    page.click("#btnReglagesClose"); page.wait_for_timeout(100)
    R.verifier(page.evaluate("document.getElementById('reglagesPanel').hidden"), "Reglages : ✕ ferme toujours")
    page.evaluate("ouvrirReglages()"); page.wait_for_timeout(120)
    page.keyboard.press("Escape"); page.wait_for_timeout(100)
    R.verifier(page.evaluate("document.getElementById('reglagesPanel').hidden"), "Reglages rouverts : propres, Echap ferme")
    # ---- Scinder un lot : meme protection
    page.evaluate("id => ouvrirFenetreScission(id)", ids_lot["Casques Boreo"]); page.wait_for_timeout(150)
    ws = page.evaluate("document.querySelector('#scissionModale .reglages-modale').getBoundingClientRect().width")
    R.verifier(ws == 1040, "Scinder : meme largeur que les autres fenetres (%d px)" % ws)
    page.mouse.click(8, 450); page.wait_for_timeout(100)
    R.verifier(page.query_selector("#scissionModale") is None, "Scinder sans saisie : un clic a cote ferme")
    page.evaluate("id => ouvrirFenetreScission(id)", ids_lot["Casques Boreo"]); page.wait_for_timeout(150)
    cb = page.query_selector("#scissionListe input[type=checkbox]")
    if cb: cb.check()
    else: page.fill("#scissionModale input[type=text]", "Nouveau lot")
    page.mouse.click(8, 450); page.wait_for_timeout(100)
    R.verifier(page.query_selector("#scissionModale") is not None, "Scinder apres saisie : le clic a cote ne ferme pas")
    page.click("#scissionClose"); page.wait_for_timeout(100)
    R.verifier(page.query_selector("#scissionModale") is None, "Scinder : ✕ ferme toujours")
    # ---- aide : meme largeur
    page.evaluate("ouvrirAide()"); page.wait_for_timeout(120)
    wa = page.evaluate("document.querySelector('#aidePanel .aide-modale').getBoundingClientRect().width")
    R.verifier(wa == 1040, "Aide : meme largeur que les autres fenetres (%d px)" % wa)
    page.evaluate("fermerAide()"); page.wait_for_timeout(80)
    # ---- telephone : plein ecran
    page.set_viewport_size({"width": 390, "height": 844}); page.wait_for_timeout(150)
    page.evaluate("() => naviguer('materiel')"); page.wait_for_timeout(150)
    page.evaluate("id => openEditor('materiel', id)", ids_mat["CAS-002"]); page.wait_for_timeout(150)
    bb = page.evaluate("(() => { const r = document.getElementById('materiel-editor').getBoundingClientRect(); return [r.x, r.y, r.width, r.height]; })()")
    R.verifier(bb[0] == 0 and bb[1] == 0 and bb[2] == 390 and bb[3] == 844, "telephone : la fenetre prend tout l'ecran %s" % bb)
    R.verifier(page.is_visible("#materiel-editor .ed-save"), "telephone : Enregistrer visible sans defiler (barre du bas fixe)")
    R.verifier(not page.erreurs, "aucune erreur JS %s" % page.erreurs)
sys.exit(R.bilan())
